    val pressed: Int,
    val selection: Int,
    val onSelection: Int,
    val selectionInactive: Int,
    val focusRing: Int,
    val destructive: Int,
    val success: Int,
    val warning: Int,
    val trafficClose: Int,
    val trafficMinimize: Int,
    val trafficMaximize: Int,
    val trafficInactive: Int,
    /** Scrim behind modal dialogs. */
